const std::array<HeroDefinition, HeroSystem::kHeroCount>& HeroSystem::Definitions()
{
    return BuildDefinitions();
}

const HeroDefinition& HeroSystem::GetDefinition(HeroId id)
{
    const auto& definitions = Definitions();
    const auto it = std::find_if(
        definitions.begin(),
        definitions.end(),
        [id](const HeroDefinition& definition)
        {
            return definition.id == id;
        });
    return it != definitions.end() ? *it : definitions.front();
}

const HeroDefinition& HeroSystem::GetDefinitionByIndex(int index)
{
    const auto& definitions = Definitions();
    const int safeIndex = std::clamp(index, 0, static_cast<int>(definitions.size()) - 1);
    return definitions[safeIndex];
}

HeroId HeroSystem::IdFromIndex(int index)
{
    return GetDefinitionByIndex(index).id;
}

int HeroSystem::IndexOf(HeroId id)
{
    const auto& definitions = Definitions();
    for (int i = 0; i < static_cast<int>(definitions.size()); ++i)
    {
        if (definitions[i].id == id)
        {
            return i;
        }
    }
    return 0;
}
